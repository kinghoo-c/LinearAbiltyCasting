/**
 * 帧计时器。
 *
 * 单位一律是秒（不是毫秒），与 three 的动画、阻尼、着色器里的 uTime 同一口径。
 * 全项目的用法只有两处：两个 App 在每帧开头 `const raw = this.time.tick()`，
 * 以及在循环正式启动前 `this.time.reset()` 一次。
 *
 * 【为什么不用 three 内置的 Clock】
 *
 * three r183 起 Clock 已废弃——它的构造函数里就带着
 * `warn('Clock: This module has been deprecated. Please use THREE.Timer instead.')`
 *（见 three.core.js），官方指定的替代品是 `THREE.Timer`。但"废弃"只是表层理由，
 * 真正让这个 30 行的类划算的是另外三点：
 *
 * 1. Clock 不钳制 delta。`getDelta()` 就是 `(performance.now() - oldTime) / 1000`
 *    原样返回：切走标签页几分钟再回来、或首次编译着色器卡一下，那几十秒会原封
 *    不动喂给模拟。要挡住它就得自己写钳制——既然要写，不如三行一起算完。
 * 2. Clock 的两个读数会互相偷时间。`getElapsedTime()` 内部会调一次 `getDelta()`，
 *    把这段时间**消费掉**；一帧里同时要 delta 和 elapsed 时，后调的那个拿到接近
 *    0 的值。`tick()` 则是"算一次步长、顺手累加、一起返回"，没有这个陷阱。
 * 3. Clock 是个状态机（autoStart / running / startTime / oldTime），首次
 *    `getDelta()` 会隐式 `start()` 并返回 0；而这里需要的是"构造即开始计时，
 *    资源加载完再显式 `reset()` 一次"——`load()` 会花掉好几秒，不该算进第一帧。
 *
 * 官方替代品 Timer 也考虑过：它用 Page Visibility API 挡住了标签页这一种情况
 *（`connect(document)` 之后 hidden 期间 delta 记 0，重新可见时把时间基准拉回
 * 现在），但挡不住长着色器编译、GC 卡顿、系统休眠，而且**同样没有钳制**——换
 * 成 Timer 仍然得自己写钳制，省不下几行。现在这样换来的是"一次调用同时给出
 * delta 与 elapsed + 无条件钳制 + 可以在控制台里直接读改的平直字段"。
 *
 * 【maxDelta 的单位与两侧的取舍】
 *
 * 单位是**秒**，不是帧率：`maxDelta = 1 / 20` 读作"单帧最多算 1/20 秒"，等价于
 * "允许最慢 20 FPS"。所以这个值往两头调都有代价：
 *
 * - 往大调 = 关掉保护。`maxDelta = 60` 意味着允许单帧走 60 秒，现实中不可能触发，
 *   钳制等于不存在。后果是卡顿之后的那一帧会把巨大的 dt 灌给所有系统：相机阻尼
 *   的 `Math.pow(rate, dt)` 直接归零、一帧内瞬移到位（取景与缩放失去全部平滑）；
 *   角色动画按秒跳相位，正在播的施放动画会一帧播完；完整版里刚放出的法术寿命
 *   瞬间走完、镜头抖动与闪光一帧归零；最贵的是几处"按 dt 推进的 while 循环"
 *  （例如 IceAbility 里铺白霜的那个），循环次数正比于 dt——冰脉 26 m/s × 60 s
 *   约 1560 m，按 3.6 块/米算就是一帧里跑约 5600 次；粒子池有容量上限，内存不会
 *   爆，但这一帧会卡成幻灯片。
 * - 往小调 = 全场慢放。这个值实质是"帧率下限开关"：设成 1/60 而机器只跑 30 FPS
 *   时，每帧那 0.033 s 会被钳成 0.0167 s，于是每秒只推进半秒的模拟时间，一切
 *   慢放一半——连相机阻尼都跟着慢，因为相机吃的 `raw` 也出自同一个钳制值。
 *
 * 所以 1/20 是刻意留出的余量：低端机与偶发卡顿最多让模拟落后于真实时间，而不是
 * 崩坏。要改就直接改这个字段（构造参数或控制台里都行）。
 */
export class Time {
    /**
     * @param {number} [maxDelta] 单帧步长上限（秒）。默认 1/20 s，也就是 20 FPS：
     *   比这更慢的帧会被当成 1/20 s 处理，模拟于是走得比真实时间慢。
     */
    constructor(maxDelta = 1 / 45) {
        /**
         * 单帧步长上限，秒。为什么必须有它：切走标签页后，浏览器对 hidden 页签的
         * rAF 多半不是立刻清零，而是节流到约 1 次/秒（有的环境/版本会彻底停掉，
         * 见 Page Lifecycle 的 frozen 状态），于是回来时 `now - _last` 常见是 ~1 秒、
         * 彻底挂起后可能是几十秒；首次编译着色器、或系统卡一下，也会攒出半秒以上
         * 的间隔。这些值原样喂给模拟，粒子会瞬移、动画会跳帧、拖尾会拉出几十米。
         * 钳住之后，最坏的结果只是"模拟落后于真实时间"，而不是画面崩坏。
         */
        this.maxDelta = maxDelta;

        /**
         * 累计秒数，每帧在 `tick()` 里加上*钳制后*的步长——也就是说超过 maxDelta
         * 的那部分时间被丢掉了，它衡量的是"模拟走过的时间"，不是墙上时钟。
         * 适合当"从启动到现在"的相位用。
         *
         * 注意：App 与 App_ground 各自另有一份 `this.elapsed`，那一份会乘上全局
         * 时间缩放（settings.global.timeScale），这一份不会——所以改变缩放只影响
         * 应用那份，这里的时钟始终与真实时间同速。当前两个 App 都不读这个字段。
         */
        this.elapsed = 0;

        /**
         * 上一次 `tick()` 返回的步长（秒，已钳制）。它只是把结果留个底，方便在
         * `tick()` 之外读"上一帧走了多久"，不必自己再算一遍；开始时为 0，
         * 表示还没有过任何一帧。当前两个 App 都不读它。
         */
        this.delta = 0;

        /**
         * 上一帧的时间戳（秒，`performance.now()` 口径），只在内部使用，
         * 所以带下划线。它是计时器唯一的"记忆"——`tick()` 靠它与当前时刻相减
         * 得到步长，`reset()` 靠它把时间基准拉回现在。用 performance.now() 而非
         * Date.now()，是因为它单调递增（改系统时间不影响它）且精度更高。
         */
        this._last = performance.now() / 1000;
    }

    /**
     * 推进计时器，返回这一帧应该走多少秒。
     * 【详解】三件事，顺序不能换：取当前时刻 → 相减得到步长并钳制 → 更新基准、
     * 累加 elapsed。钳制放在这里，是因为只有它知道"两帧之间到底隔了多久"。
     *
     * 一个容易写错的细节：`_last` 记的是**未经钳制的当前时刻**，而不是
     * "上一帧 + 钳后的步长"。若按后者写，一次长暂停之后计时器就永远追不上真实
     * 时间，误差会越积越多；现在这样写，丢弃的只是那一帧多出来的部分，下一帧就
     * 重新对齐了。
     *
     * @returns {number} 距上一次 tick 的秒数，已做钳制
     */
    tick() {
        const now = performance.now() / 1000;
        this.delta = Math.min(now - this._last, this.maxDelta);
        this._last = now;
        this.elapsed += this.delta;
        return this.delta;
    }

    /**
     * 长时间暂停（资源加载、切换标签页）之后调用，以避免时间跳变。
     * 【详解】只重置内部记账：把 `_last` 拉回"现在"、`delta` 归零。它**不动**
     * `elapsed`——累计时间不倒退，否则一切以它为相位的动画会倒着放。
     * 两个 App 都在 `load()` 结束、循环正式启动之前调用一次，好让加载资源那几秒
     * 不被算进第一帧（否则第一帧的步长会被钳到 maxDelta 上限，模拟凭空多走 1/20 s）。
     */
    reset() {
        this._last = performance.now() / 1000;
        this.delta = 0;
    }
}
